    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (jTextField5.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese su número de cuenta.");
            return;
        }

        if (jTextField4.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Calcule el total antes de realizar la compra.");
            return;
        }
        int cantidad = (int) jSpinner1.getValue();
        double total = cantidad * precioUnitario;
        GestionLive gestion = new GestionLive();
        gestion.actualizarReservas();
        boolean autoCommit = true;
        try {
            autoCommit = conn.getAutoCommit();
            conn.setAutoCommit(false);
            // Verificar estado del Live
            String sql = "SELECT estado FROM lives WHERE id_live = ? FOR UPDATE";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setInt(1, idLive);
            ResultSet rs = ps.executeQuery();

            if (!rs.next() || !rs.getString("estado").equals("EN_CURSO")) {
                conn.rollback();
                JOptionPane.showMessageDialog(this,
                        "Este Live ya no está disponible.");
                return;
            }
            rs.close();
            ps.close();
            // Descontar stock
            sql = "UPDATE live_productos lp "
                    + "SET lp.cantidad = lp.cantidad - ? "
                    + "WHERE lp.id_live = ? AND lp.id_producto = ? "
                    + "AND lp.cantidad - ("
                    + "SELECT COALESCE(SUM(a.cantidad), 0) "
                    + "FROM apartados a "
                    + "WHERE a.id_live = ? AND a.id_producto = ? "
                    + "AND a.estado = 'ACTIVO') >= ?";
            ps = conn.prepareStatement(sql);
            ps.setInt(1, cantidad);
            ps.setInt(2, idLive);
            ps.setInt(3, idProducto);
            ps.setInt(4, idLive);
            ps.setInt(5, idProducto);
            ps.setInt(6, cantidad);
            if (ps.executeUpdate() == 0) {
                conn.rollback();
                JOptionPane.showMessageDialog(this,
                        "No hay suficiente stock disponible.");
                ps.close();
                return;
            }
            ps.close();
            // Registrar venta
           sql = "INSERT INTO ventas "
            + "(id_cliente, fecha_hora, canal, id_live, id_pedido, total, estado) "
            + "VALUES (?, NOW(), 'LIVE', ?, 0, ?, 'Y')";
            ps = conn.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
            ps.setInt(1, idUsuario);
            ps.setInt(2, idLive);
            ps.setDouble(3, total);
            ps.executeUpdate();
            rs = ps.getGeneratedKeys();
            if (!rs.next()) {
                throw new Exception("No se pudo obtener el ID de la venta.");
            }

            int idVenta = rs.getInt(1);
            rs.close();
            ps.close();
            // Registrar detalle
            sql = "INSERT INTO detalle_ventas "
                    + "(id_venta, id_producto, cantidad, precio_unitario, descuento, subtotal) "
                    + "VALUES (?, ?, ?, ?, 0, ?)";

            ps = conn.prepareStatement(sql);
            ps.setInt(1, idVenta);
            ps.setInt(2, idProducto);
            ps.setInt(3, cantidad);
            ps.setDouble(4, precioUnitario);
            ps.setDouble(5, total);
            ps.executeUpdate();
            ps.close();

            conn.commit();
            JOptionPane.showMessageDialog(this,
                    "Compra realizada correctamente.");
            ventanaUsuario.cargarProductos();
            this.dispose();
        } catch (Exception e) {
            try {
                conn.rollback();
            } catch (Exception ex) {
                System.out.println(ex.getMessage());
            }
            JOptionPane.showMessageDialog(this,
                    "Error al realizar la compra: " + e.getMessage());

        } finally {
            try {
                conn.setAutoCommit(autoCommit);
            } catch (Exception e) {
                System.out.println(e.getMessage());
            }
        }
        // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

