    void cargarUsuario() {
        try {
            int idUsuario = Integer.parseInt(jTextField2.getText());

            String sql = "SELECT u.usuario_plataforma "
                   + "FROM clientes u "
                   + "WHERE u.id_cliente = ?";

            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setInt(1, idUsuario);

            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                String nombre = rs.getString("usuario_plataforma");
                jTextField1.setText(nombre);
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }
    
