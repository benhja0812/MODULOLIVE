    private void programarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_programarActionPerformed
        if (model.getRowCount() == 0) {
          JOptionPane.showMessageDialog(
            this, "Debe agregar al menos un producto.");
            return;
        }

        if (jDateChooser1.getDate() == null) {
            JOptionPane.showMessageDialog(
                this, "Seleccione una fecha.");
            return;
        }

        Date horaInicial = (Date) horaInicio.getValue();
        Date horaFin = (Date) horaFinal.getValue();

        Calendar calInicio = Calendar.getInstance();
        calInicio.setTime(horaInicial);

        Calendar calFin = Calendar.getInstance();
        calFin.setTime(horaFin);

        int minutosInicio = calInicio.get(Calendar.HOUR_OF_DAY) * 60
                          + calInicio.get(Calendar.MINUTE);

        int minutosFin = calFin.get(Calendar.HOUR_OF_DAY) * 60
                       + calFin.get(Calendar.MINUTE);

        int duracion = minutosFin - minutosInicio;

        if (duracion <= 0) {
            JOptionPane.showMessageDialog(
                this, "La hora final debe ser posterior a la hora de inicio.");
            return;
        }

        if (duracion < 15) {
            JOptionPane.showMessageDialog(
                this, "El directo debe durar como mínimo 15 minutos.");
            return;
        }

        try {
            java.sql.Date fechaSQL =
                new java.sql.Date(jDateChooser1.getDate().getTime());

            java.sql.Time horaInicioSQL =
                new java.sql.Time(horaInicial.getTime());

            java.sql.Time horaFinSQL =
                new java.sql.Time(horaFin.getTime());

            int anfitrion = Integer.parseInt(jTextField2.getText());

            // 1. Verificar que el anfitrión exista en usuarios.
            String sqlAnfitrion =
                "SELECT id_usuario FROM usuarios WHERE id_usuario = ?";

            PreparedStatement psAnfitrion =
                conn.prepareStatement(sqlAnfitrion);

            psAnfitrion.setInt(1, anfitrion);

            ResultSet rsAnfitrion = psAnfitrion.executeQuery();

            if (!rsAnfitrion.next()) {
                JOptionPane.showMessageDialog(
                    this, "El anfitrión no existe.");
                return;
            }

            rsAnfitrion.close();
            psAnfitrion.close();

            // 2. Verificar que el anfitrión no tenga otro Live en ese horario.
            String sqlConflicto =
                "SELECT id_live FROM lives "
                + "WHERE fecha = ? "
                + "AND id_anfitrion = ? "
                + "AND estado IN ('PROGRAMADO', 'EN_CURSO') "
                + "AND hora_inicio < ? "
                + "AND hora_fin > ?";

            PreparedStatement psConflicto =
                conn.prepareStatement(sqlConflicto);

            psConflicto.setDate(1, fechaSQL);
            psConflicto.setInt(2, anfitrion);
            psConflicto.setTime(3, horaFinSQL);
            psConflicto.setTime(4, horaInicioSQL);

            ResultSet rsConflicto = psConflicto.executeQuery();

            if (rsConflicto.next()) {
                JOptionPane.showMessageDialog(
                    this,
                    "El anfitrión ya tiene un directo programado en ese horario.");
                return;
            }

            rsConflicto.close();
            psConflicto.close();

            // 3. Registrar el Live.
            String sql = "INSERT INTO lives "
                + "(fecha, hora_inicio, hora_fin, id_anfitrion, estado) "
                + "VALUES (?, ?, ?, ?, ?)";

            PreparedStatement ps = conn.prepareStatement(
                sql, Statement.RETURN_GENERATED_KEYS);

            ps.setDate(1, fechaSQL);
            ps.setTime(2, horaInicioSQL);
            ps.setTime(3, horaFinSQL);
            ps.setInt(4, anfitrion);
            ps.setString(5, "PROGRAMADO");

            ps.executeUpdate();

            ResultSet rs = ps.getGeneratedKeys();

            int idLive = 0;

            if (rs.next()) {
                idLive = rs.getInt(1);
            } else {
                JOptionPane.showMessageDialog(
                    this, "No se pudo obtener el ID del directo.");
                return;
            }

            rs.close();
            ps.close();

            // 4. Registrar los productos del Live.
            String sqlProducto = "INSERT INTO live_productos "
                + "(id_live, id_producto, precio_live, cantidad) "
                + "VALUES (?, ?, ?, ?)";

            PreparedStatement psProducto =
                conn.prepareStatement(sqlProducto);

            for (int fila = 0; fila < model.getRowCount(); fila++) {

                int idProducto = Integer.parseInt(
                    model.getValueAt(fila, 0).toString());

                int cantidad = Integer.parseInt(
                    model.getValueAt(fila, 2).toString());

                String precioTexto =
                    model.getValueAt(fila, 3).toString();

                precioTexto = precioTexto.replace("Bs ", "");
                precioTexto = precioTexto.replace(",", ".");

                double precio = Double.parseDouble(precioTexto);

                psProducto.setInt(1, idLive);
                psProducto.setInt(2, idProducto);
                psProducto.setDouble(3, precio);
                psProducto.setInt(4, cantidad);

                psProducto.executeUpdate();
            }

            psProducto.close();

            JOptionPane.showMessageDialog(
                this,
                "Directo programado correctamente.\n"
                + "ID del directo: " + idLive);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                this,
                "Error al programar el directo: " + e.getMessage());
        }
        // TODO add your handling code here:
    }//GEN-LAST:event_programarActionPerformed

