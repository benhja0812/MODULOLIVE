    void cargarNombreAnfitrion() {
        try {
            int idAnfitrion = Integer.parseInt(jTextField2.getText());

            String sql = "SELECT nombre, apellido FROM usuarios "
                       + "WHERE id_usuario = ?";

            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setInt(1, idAnfitrion);

            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                String nombre = rs.getString("nombre");
                String apellido = rs.getString("apellido");

                jTextField1.setText(nombre + " " + apellido);
            } else {
                jTextField1.setText("Anfitrión no encontrado");
            }

            rs.close();
            ps.close();

        } catch (NumberFormatException e) {
            jTextField1.setText("ID inválido");

        } catch (Exception e) {
            jTextField1.setText("Error al buscar");
        }
    }
    
    
