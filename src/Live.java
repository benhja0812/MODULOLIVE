    private void agregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_agregarActionPerformed
        try {
            String producto = tablaProducto.getSelectedItem().toString();
            int cantidad = (int) cantidadProducto.getValue();
            String sql = "SELECT id_producto, precio_venta FROM productos WHERE nombre = ?";

            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, producto);
            ResultSet rs = ps.executeQuery();
            if (rs.next()) {

                int idProducto = rs.getInt("id_producto");
                String precio = rs.getString("precio_venta");
                for (int i = 0; i < model.getRowCount(); i++) {
                    int idExistente = Integer.parseInt(
                        model.getValueAt(i, 0).toString());

                    if (idExistente == idProducto) {
                        JOptionPane.showMessageDialog(
                            this, "El producto ya fue agregado al live, si desea"
                            + "cambiar la cantidad del producto puede usar el boton "
                            + "de editar.");
                        return;
                    }
                }

                String sqlStock =
                "SELECT COALESCE(SUM("
                + "CASE "
                + "WHEN tipo_movimiento = 'ENTRADA' THEN cantidad "
                + "WHEN tipo_movimiento IN ('SALIDA', 'MERMA') THEN -cantidad "
                + "END), 0) AS stock "
                + "FROM movimientos_stock "
                + "WHERE id_producto = ?";

                PreparedStatement psStock =
                conn.prepareStatement(sqlStock);

                psStock.setInt(1, idProducto);

                ResultSet rsStock = psStock.executeQuery();

                int stock = 0;

                if (rsStock.next()) {
                    stock = rsStock.getInt("stock");
                }

                String sqlReservado =
                "SELECT COALESCE(SUM(lp.cantidad), 0) AS reservado "
                + "FROM live_productos lp "
                + "INNER JOIN lives l "
                + "ON lp.id_live = l.id_live "
                + "WHERE lp.id_producto = ? "
                + "AND l.estado IN ('PROGRAMADO', 'EN_CURSO')";

                PreparedStatement psReservado =
                conn.prepareStatement(sqlReservado);

                psReservado.setInt(1, idProducto);

                ResultSet rsReservado = psReservado.executeQuery();

                int reservado = 0;

                if (rsReservado.next()) {
                    reservado = rsReservado.getInt("reservado");
                }

                int disponible = stock - reservado;

                if (cantidad > disponible) {

                    JOptionPane.showMessageDialog(
                        this,
                        "No hay suficiente stock disponible.\n"
                        + "Stock físico: " + stock + "\n"
                        + "Reservado en otros lives: " + reservado + "\n"
                        + "Disponible: " + disponible
                    );

                    return;
                }

                String[] fila = new String[4];
                fila[0] = String.valueOf(idProducto);
                fila[1] = producto;
                fila[2] = String.valueOf(cantidad);
                fila[3] = String.format("Bs %.2f",Double.parseDouble(precio.replace(",", ".")));
                model.addRow(fila);
            }
        } catch (Exception e) {

            JOptionPane.showMessageDialog(null,
                "Error: " + e.getMessage());

        }
        // TODO add your handling code here:
    }//GEN-LAST:event_agregarActionPerformed

