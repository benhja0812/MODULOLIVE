    void cargarProducto() {
        String sql = "SELECT nombre "
                + "FROM productos "
                + "WHERE id_producto = ?";

        try (PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setInt(1, idProducto);

            try (ResultSet rs = ps.executeQuery()) {
                if (rs.next()) {
                    jTextField1.setText(rs.getString("nombre"));
                }
            }

            jTextField2.setText(
                    String.format("%.2f", precioUnitario).replace(".", ",")
            );

        } catch (Exception e) {
            System.out.println("Error al cargar producto: "
                    + e.getMessage());
        }
    }

    
        int obtenerMinutosRestantes() {
        int minutos = 0;

        try {
            String sql = "SELECT TIMESTAMPDIFF(MINUTE, NOW(), "
                + "TIMESTAMP(fecha, hora_fin)) AS minutos_restantes "
                + "FROM lives "
                + "WHERE id_live = ?";

            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setInt(1, idLive);

            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                minutos = rs.getInt("minutos_restantes");
            }

        } catch (Exception e) {
        System.out.println("Error al obtener tiempo restante: "
                + e.getMessage());
        }

        return minutos;
    }
    void configurarTiempo() {
    int minutosRestantes = obtenerMinutosRestantes();

    if (minutosRestantes < 1) {
        JOptionPane.showMessageDialog(this,
                "No queda tiempo suficiente para realizar una reserva.");
        dispose();
        return;
    }
        int valorInicial = Math.min(15, minutosRestantes);

        SpinnerNumberModel modelo =
            new SpinnerNumberModel(
                    valorInicial, 1,minutosRestantes,1);
        jSpinner2.setModel(modelo);
    }

