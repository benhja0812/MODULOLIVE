    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       int cantidadReservar = (int) jSpinner1.getValue();
       int minutosReserva = (int) jSpinner2.getValue();

       GestionLive gestion = new GestionLive();
       int stockActual = gestion.verificarStock(idLive, idProducto);

       if (cantidadReservar > stockActual) {
           JOptionPane.showMessageDialog(this,
               "No hay suficiente stock disponible.");
           jSpinner1.setValue(1);
           jTextField4.setText("");
           return;
       }

       try {
           String sql = "INSERT INTO apartados "
               + "(id_live, id_producto, id_cliente, cantidad, "
               + "fecha_apartado, fecha_expiracion, estado) "
               + "VALUES (?, ?, ?, ?, NOW(), "
               + "DATE_ADD(NOW(), INTERVAL ? MINUTE), 'ACTIVO')";

           PreparedStatement ps = conn.prepareStatement(sql);

           ps.setInt(1, idLive);
           ps.setInt(2, idProducto);
           ps.setInt(3, idUsuario);
           ps.setInt(4, cantidadReservar);
           ps.setInt(5, minutosReserva);

           ps.executeUpdate();
           ps.close();

           JOptionPane.showMessageDialog(this,
               "Reserva realizada correctamente.");

           if (ventanaUsuario != null) {
               ventanaUsuario.cargarProductos();
           }

           this.dispose();

       } catch (Exception e) {
           System.out.println("Error al realizar la reserva: "
               + e.getMessage());

           JOptionPane.showMessageDialog(this,
               "No se pudo realizar la reserva.");
       }
        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

