    void Llenar() {
        try {
            int idAnfitrion = Integer.parseInt(jTextField1.getText());

            String[] titulos = {
                "ID", "Fecha", "Hora inicio", "Hora fin", "Estado"
            };

            String sql = "SELECT id_live, fecha, hora_inicio, hora_fin, estado "
                       + "FROM lives "
                       + "WHERE id_anfitrion = ? "
                       + "AND estado IN ('PROGRAMADO', 'EN_CURSO') "
                       + "ORDER BY fecha, hora_inicio";

            model = new DefaultTableModel(null, titulos);

            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setInt(1, idAnfitrion);

            ResultSet rs = ps.executeQuery();

            String[] fila = new String[5];

            while (rs.next()) {
                fila[0] = rs.getString("id_live");
                fila[1] = rs.getString("fecha");
                fila[2] = rs.getString("hora_inicio");
                fila[3] = rs.getString("hora_fin");
                fila[4] = rs.getString("estado");

                model.addRow(fila);
            }

            jTable1.setModel(model);

            rs.close();
            ps.close();

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    
    void cargarNombreAnfitrion() {
        try {
            int idAnfitrion = Integer.parseInt(jTextField1.getText());

            String sql = "SELECT nombre, apellido "
                       + "FROM usuarios "
                       + "WHERE id_usuario = ?";

            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setInt(1, idAnfitrion);

            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                String nombre = rs.getString("nombre");
                String apellido = rs.getString("apellido");

                jTextField2.setText(nombre + " " + apellido);
            } else {
                jTextField2.setText("Anfitrión no encontrado");
            }

            rs.close();
            ps.close();

        } catch (NumberFormatException e) {
            jTextField2.setText("ID inválido");

        } catch (Exception e) {
            jTextField2.setText("Error al buscar");
            e.printStackTrace();
        }
    }

    
