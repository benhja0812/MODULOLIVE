    void cargarReserva() {
        try {
            String sql = "SELECT p.nombre, lp.precio_live, a.cantidad "
                + "FROM apartados a "
                + "INNER JOIN productos p "
                + "ON a.id_producto = p.id_producto "
                + "INNER JOIN live_productos lp "
                + "ON a.id_live = lp.id_live "
                + "AND a.id_producto = lp.id_producto "
                + "WHERE a.id_apartado = ? "
                + "AND a.id_cliente = ? "
                + "AND a.id_live = ?";

            PreparedStatement ps = conn.prepareStatement(sql);

            ps.setInt(1, idApartado);
            ps.setInt(2, idUsuario);
            ps.setInt(3, idLive);
            ResultSet rs = ps.executeQuery();
            if (rs.next()) {
                String nombre = rs.getString("nombre");
                double precio = rs.getDouble("precio_live");
                int cantidad = rs.getInt("cantidad");
                double total = precio * cantidad;

                jTextField1.setText(nombre);
                jTextField2.setText(
                    String.format("%.2f", precio).replace(".", ","));
                jTextField3.setText(String.valueOf(cantidad));
                jTextField4.setText(
                    String.format("%.2f", total).replace(".", ",")
                );
            }
            } catch (Exception e) {
            System.out.println("Error al cargar reserva: "
                + e.getMessage());
        }
    }
