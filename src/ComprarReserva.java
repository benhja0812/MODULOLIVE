    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String cuenta = jTextField5.getText().trim();

        if (cuenta.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese su número de cuenta.");
            return;
        }

        GestionLive gestion = new GestionLive();
        gestion.actualizarReservas();

        boolean autoCommit = true;

        try {
            autoCommit = conn.getAutoCommit();
            conn.setAutoCommit(false);

            String sql = "SELECT estado FROM lives "
                       + "WHERE id_live = ? FOR UPDATE";

            boolean liveDisponible;

            try (PreparedStatement ps = conn.prepareStatement(sql)) {
                ps.setInt(1, idLive);

                try (ResultSet rs = ps.executeQuery()) {
                    liveDisponible = rs.next()
                            && "EN_CURSO".equals(rs.getString("estado"));
                }
            }

            if (!liveDisponible) {
                conn.rollback();
                JOptionPane.showMessageDialog(this,
                        "Este Live ya no está disponible.");
                return;
            }

            sql = "SELECT a.id_producto, a.cantidad, "
                + "a.estado, lp.precio_live "
                + "FROM apartados a "
                + "INNER JOIN live_productos lp "
                + "ON a.id_live = lp.id_live "
                + "AND a.id_producto = lp.id_producto "
                + "WHERE a.id_apartado = ? "
                + "AND a.id_cliente = ? "
                + "AND a.id_live = ? FOR UPDATE";

            int idProducto;
            int cantidad;
            double precio;
            String estado;

            try (PreparedStatement ps = conn.prepareStatement(sql)) {
                ps.setInt(1, idApartado);
                ps.setInt(2, idUsuario);
                ps.setInt(3, idLive);

                try (ResultSet rs = ps.executeQuery()) {
                    if (!rs.next()) {
                        conn.rollback();
                        JOptionPane.showMessageDialog(this,
                                "No se encontró la reserva.");
                        return;
                    }

                    idProducto = rs.getInt("id_producto");
                    cantidad = rs.getInt("cantidad");
                    precio = rs.getDouble("precio_live");
                    estado = rs.getString("estado");
                }
            }

            if (!"ACTIVO".equalsIgnoreCase(estado)) {
                conn.rollback();
                JOptionPane.showMessageDialog(this,
                        "Esta reserva ya no está activa.");
                return;
            }

            double total = cantidad * precio;

            sql = "UPDATE live_productos lp "
                + "SET lp.cantidad = lp.cantidad - ? "
                + "WHERE lp.id_live = ? "
                + "AND lp.id_producto = ? "
                + "AND lp.cantidad - ("
                + "SELECT COALESCE(SUM(a.cantidad), 0) "
                + "FROM apartados a "
                + "WHERE a.id_live = ? "
                + "AND a.id_producto = ? "
                + "AND a.estado = 'ACTIVO' "
                + "AND a.id_apartado <> ?) >= ?";

            try (PreparedStatement ps = conn.prepareStatement(sql)) {
                ps.setInt(1, cantidad);
                ps.setInt(2, idLive);
                ps.setInt(3, idProducto);
                ps.setInt(4, idLive);
                ps.setInt(5, idProducto);
                ps.setInt(6, idApartado);
                ps.setInt(7, cantidad);

                if (ps.executeUpdate() == 0) {
                    conn.rollback();
                    JOptionPane.showMessageDialog(this,
                            "No hay suficiente stock disponible.");
                    return;
                }
            }

            sql = "INSERT INTO ventas "
                + "(id_cliente, fecha_hora, canal, id_live, "
                + "id_pedido, total, estado) "
                + "VALUES (?, NOW(), 'LIVE', ?, 0, ?, 'Y')";

            int idVenta;

            try (PreparedStatement ps = conn.prepareStatement(
                    sql, Statement.RETURN_GENERATED_KEYS)) {

                ps.setInt(1, idUsuario);
                ps.setInt(2, idLive);
                ps.setDouble(3, total);

                ps.executeUpdate();

                try (ResultSet rs = ps.getGeneratedKeys()) {
                    if (!rs.next()) {
                        throw new Exception(
                                "No se pudo obtener el ID de la venta.");
                    }

                    idVenta = rs.getInt(1);
                }
            }

            sql = "INSERT INTO detalle_ventas "
                + "(id_venta, id_producto, cantidad, "
                + "precio_unitario, descuento, subtotal) "
                + "VALUES (?, ?, ?, ?, 0, ?)";

            try (PreparedStatement ps = conn.prepareStatement(sql)) {
                ps.setInt(1, idVenta);
                ps.setInt(2, idProducto);
                ps.setInt(3, cantidad);
                ps.setDouble(4, precio);
                ps.setDouble(5, total);

                ps.executeUpdate();
            }

            sql = "UPDATE apartados "
                + "SET estado = 'CONFIRMADO' "
                + "WHERE id_apartado = ? "
                + "AND id_cliente = ? "
                + "AND id_live = ? "
                + "AND estado = 'ACTIVO'";

            try (PreparedStatement ps = conn.prepareStatement(sql)) {
                ps.setInt(1, idApartado);
                ps.setInt(2, idUsuario);
                ps.setInt(3, idLive);

                if (ps.executeUpdate() == 0) {
                    throw new Exception(
                            "No se pudo confirmar la reserva.");
                }
            }

            conn.commit();

            JOptionPane.showMessageDialog(this,
                    "Compra realizada correctamente.");

            ventanaReservas.cargarReservas();
            this.dispose();

        } catch (Exception e) {
            try {
                conn.rollback();
            } catch (Exception ex) {
                System.out.println("Error al revertir: "
                        + ex.getMessage());
            }

            JOptionPane.showMessageDialog(this,
                    "Error al comprar la reserva: " + e.getMessage());

        } finally {
            try {
                conn.setAutoCommit(autoCommit);
            } catch (Exception e) {
                System.out.println("Error al restaurar conexión: "
                        + e.getMessage());
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

