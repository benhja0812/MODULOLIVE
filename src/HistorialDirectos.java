    void cargarFinalizados() {
        try {
            int idAnfitrion = Integer.parseInt(jTextField2.getText());

            String[] titulos = {
                "ID Live", "Fecha", "Hora inicio",
                "Hora fin", "Estado", "Ganancias"
            };

            String sql = "SELECT l.id_live, l.fecha, "
                    + "l.hora_inicio, l.hora_fin, l.estado, "
                    + "COALESCE(SUM(v.total), 0) AS ganancias "
                    + "FROM lives l "
                    + "LEFT JOIN ventas v "
                    + "ON l.id_live = v.id_live "
                    + "AND v.canal = 'LIVE' "
                    + "WHERE l.id_anfitrion = ? "
                    + "AND l.estado = 'CERRADO' "
                    + "GROUP BY l.id_live, l.fecha, "
                    + "l.hora_inicio, l.hora_fin, l.estado "
                    + "ORDER BY l.fecha, l.hora_inicio";

            model = new DefaultTableModel(null, titulos);

            try (PreparedStatement ps = conn.prepareStatement(sql)) {
                ps.setInt(1, idAnfitrion);

                try (ResultSet rs = ps.executeQuery()) {
                    while (rs.next()) {
                        String[] fila = new String[6];

                        fila[0] = rs.getString("id_live");
                        fila[1] = rs.getString("fecha");
                        fila[2] = rs.getString("hora_inicio");
                        fila[3] = rs.getString("hora_fin");
                        fila[4] = rs.getString("estado");

                        fila[5] = String.format(
                                java.util.Locale.US,
                                "%.2f",
                                rs.getDouble("ganancias")
                        );

                        model.addRow(fila);
                    }
                }
            }

            jTable1.setModel(model);

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                    "El ID del anfitrión no es válido.");
        } catch (Exception e) {
            System.out.println("Error al cargar historial: "
                    + e.getMessage());
            e.printStackTrace();
        }
    }

    
    
